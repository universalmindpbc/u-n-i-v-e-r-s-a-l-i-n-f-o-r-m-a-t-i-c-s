"""Extract reusable heavy-atom templates from BioExcel's NAB lbdna fixture.

The fixture is a regular, modelled duplex. Inverse screw transforms recover
the four nucleotide templates on each strand, without fitting a gene fold.
"""
import hashlib
import json
import math
from pathlib import Path

ROOT = Path(__file__).resolve().parent
SOURCE = ROOT / 'dna-model-source/nab-lbdna-reference.pdb'
RISE, TWIST = 3.38, 36.0
residues = {}
for line in SOURCE.read_text().splitlines():
    if not line.startswith('ATOM') or line[76:78].strip() == 'H':
        continue
    n = int(line[22:26])
    r = residues.setdefault(n, {'base': line[17:20].strip()[1:], 'atoms': []})
    r['atoms'].append([line[12:16].strip(), line[76:78].strip(),
                      *[float(line[i:i+8]) for i in (30, 38, 46)]])
n = len(residues) // 2
sequence = ''.join(residues[i]['base'] for i in range(1, n+1))
assert sequence == 'GCGCGGCTGATAAACGAAAGC'
templates = {'A': {}, 'B': {}}
samples = {'A': {}, 'B': {}}
for number, residue in residues.items():
    strand = 'A' if number <= n else 'B'
    pair = number-1 if strand == 'A' else 2*n-number
    if pair in (0, n-1):
        continue  # exclude terminal chemistry
    angle = -pair * math.radians(TWIST)
    atoms = [[name, element,
              x*math.cos(angle)-y*math.sin(angle),
              x*math.sin(angle)+y*math.cos(angle), z-pair*RISE]
             for name, element, x, y, z in residue['atoms']]
    samples[strand].setdefault(residue['base'], []).append(atoms)
maximum_error = 0.0
for strand, bases in samples.items():
    assert set(bases) == set('ACGT')
    for base, examples in bases.items():
        first = examples[0]
        average = []
        for i, atom in enumerate(first):
            assert all(e[i][:2] == atom[:2] for e in examples)
            mean = [sum(e[i][axis] for e in examples)/len(examples) for axis in (2,3,4)]
            maximum_error = max(maximum_error, *[math.dist(e[i][2:], mean) for e in examples])
            average.append([*atom[:2], *[round(x,6) for x in mean]])
        templates[strand][base] = average
assert maximum_error < .002, maximum_error
metadata = {
    'id': 'nab-lbdna-heavy-atoms-v1',
    'name': 'Ideal B-DNA atomic model',
    'method': 'Sequence assembled from NAB Langridge B-DNA heavy-atom templates',
    'riseAngstrom': RISE, 'twistDegrees': TWIST,
    'referenceSHA256': hashlib.sha256(SOURCE.read_bytes()).hexdigest(),
    'referenceSource': 'https://github.com/bioexcel/biobb_amber/blob/35751118940efeccc430cb53c96b174c6ba7b52c/biobb_amber/test/reference/nab/ref_nab_build_dna_structure.pdb',
    'builderSource': 'https://github.com/bioexcel/biobb_amber/blob/bf9be6288f10f0d44077058c35fb84148c166a63/biobb_amber/nab/nab_build_dna_structure.py',
    'templateMaximumDeviationAngstrom': maximum_error,
    'hydrogens': 'omitted',
    'interpretation': 'Constructed ideal B-DNA; no experimental gene fold, sequence-dependent relaxation or cellular chromatin conformation is inferred.'
}
(ROOT/'dna-templates.js').write_text('// Generated by build-dna-templates.py from the cited BioExcel reference.\n'
    +'export const dnaModelSource='+json.dumps(metadata, separators=(',', ':'))+';\n'
    +'export const dnaTemplates='+json.dumps(templates, separators=(',', ':'))+';\n')
print(json.dumps({'templates': 8, 'maxDeviationAngstrom': maximum_error, 'referenceSHA256': metadata['referenceSHA256']}))
