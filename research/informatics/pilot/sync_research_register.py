"""Attach the shared literature collection without changing mathematical observations.

Run after geometry generation and before export_csv.py. Individual records are
self-contained; dataset.json includes the bibliography once, keyed by study ID.
"""
import argparse
import json
from pathlib import Path


def write_json(path, data):
    path.write_text(json.dumps(data, ensure_ascii=False, indent=2) + '\n')


def validate(register):
    papers = register['publications']
    ids = [p['id'] for p in papers]
    assert len(ids) == len(set(ids)) == register['publication_count'] == 14
    assert len({p['doi'].lower() for p in papers}) == 14
    assert register['hero_publication_ids'] == [p['id'] for p in papers if p['hero']]
    assert {p['hero'] for p in papers if p['hero']} == {'alpha', 'beta', 'gamma', 'epsilon'}
    assert register['wss']['score'] is None
    for p in papers:
        assert p['score'] == sum(p['scoreParts'].values())
        assert all(0 <= v <= register['appraisal_method']['components'][k]['range'][1]
                   for k, v in p['scoreParts'].items())
        assert p['jadad'] == 'Not applicable'
        assert all(p[k] for k in ('title', 'doi', 'methods', 'finding', 'limit', 'access'))


def sync(data_dir, source, browser_js=None):
    register = json.loads(source.read_text())
    validate(register)
    dataset = json.loads((data_dir / 'dataset.json').read_text())
    assert sorted(r['modulus'] for r in dataset['records']) == list(range(1, 49))
    reference = {
        'register_id': register['id'], 'register_version': register['version'],
        'register_file': 'research-register.json',
        'relationship': 'background_context',
        'scope': register['scope'],
        'publication_ids': [p['id'] for p in register['publications']],
        'hero_publication_ids': register['hero_publication_ids'],
        'modulus_relevance_status': 'Not yet assessed',
    }
    for record in dataset['records']:
        # Never populate tier evidence from shared background literature.
        assert all(t['wss_score'] is None and t['evidence'] == [] for t in record['research']['tiers'])
        record['schema_version'] = '2.2.0'
        record['research']['background_literature'] = reference
        record.pop('research_register', None)
        write_json(data_dir / f"m{record['modulus']}.json", {**record, 'research_register': register})
    dataset['schema_version'] = '2.2.0'
    dataset['research_register'] = register
    write_json(data_dir / 'dataset.json', dataset)
    write_json(data_dir / 'research-register.json', register)
    index = json.loads((data_dir / 'index.json').read_text())
    index['research_register'] = {
        'id': register['id'], 'version': register['version'],
        'file': 'pilot-v1/research-register.json',
    }
    write_json(data_dir / 'index.json', index)
    if browser_js:
        browser_js.write_text("'use strict';\n// Generated by sync_research_register.py from research/informatics/research-register.json.\n"
                             '// Edit the canonical JSON and regenerate all exports together.\n'
                             'window.InformaticsResearchRegister = '
                             + json.dumps(register, ensure_ascii=False, indent=2)
                             + ';\nwindow.InformaticsStudies = window.InformaticsResearchRegister.publications;\n')
    return register


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--data-dir', required=True, type=Path)
    parser.add_argument('--source', type=Path, default=Path(__file__).resolve().parents[1] / 'research-register.json')
    parser.add_argument('--browser-js', type=Path)
    args = parser.parse_args()
    result = sync(args.data_dir, args.source, args.browser_js)
    print(f"Attached {result['id']} {result['version']}: 48 records, 14 papers, 4 HERO references; WSS unassigned.")
